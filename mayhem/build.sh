#!/usr/bin/env bash
# mayhem/build.sh — build the TreeSheets fuzz harnesses and the test oracle.
# TreeSheets is one unity TU (src/main.cpp) linked against wxWidgets (GTK3), Monocypher and
# libunibreak, which upstream's CMake FetchContents; the Dockerfile caches them prebuilt under
# /opt/toolchains/deps. The harness TU (mayhem/harnesses/ts_fuzz.cpp) includes src/main.cpp, so the
# whole application is compiled with the sanitizer flags.
set -euo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH
: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
: "${SRC:=/mayhem}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
cd "$SRC"

DEPS=/opt/toolchains/deps
WX=$DEPS/wxwidgets-3.3.4
MONO=$DEPS/monocypher-4.0.3
UB=$DEPS/libunibreak-8.0
LOB=$DEPS/lobster-2026.9
B=$SRC/mayhem/build
GEN=$B/generated
mkdir -p "$GEN"

# Embedded data headers, generated by upstream's own cmake/EmbedFiles.cmake script mode.
embed() {  # name dir find-args...
  local name=$1 dir=$2; shift 2
  (cd "$dir" && find . "$@" -type f | LC_ALL=C sort | sed "s|^\./|$dir/|") > "$GEN/embedded_$name.txt"
  cmake -DNAME="$name" -DDIR="$dir" -DLIST="$GEN/embedded_$name.txt" -DOUTPUT="$GEN/embedded_$name.h" \
        -P "$SRC/cmake/EmbedFiles.cmake"
}
embed images "$SRC/TS/images" \( -name '*.png' -o -name '*.svg' \)
embed translations "$SRC/TS/translations" -name '*.mo'
embed lobster "$LOB/src" \( -path ./modules/std.lobster -o -path ./modules/stdtype.lobster -o -path ./modules/vec.lobster -o -path ./modules/color.lobster \)
embed examples "$SRC/TS" \( -path './examples/tutorial*.cts' -o -path './examples/operation-reference*.cts' \) -not -path './examples/*/*'

WXCXX="$("$WX/bin/wx-config" --cxxflags aui,adv,core,xml,net)"
WXLIBS="$("$WX/bin/wx-config" --libs aui,adv,core,xml,net)"
GTKCFLAGS="$(pkg-config --cflags gtk+-3.0)"
GTKLIBS="$(pkg-config --libs gtk+-3.0)"
LOBINC="-I$LOB/src/dev/src -I$LOB/src/dev/include -I$LOB/src/dev/external -I$LOB/src/dev/external/libtcc"
DEFS="-DPACKAGE_VERSION=\"mayhem\" -DTREESHEETS_USE_PANGO -DENABLE_LOBSTER=1 -I$SRC/src -I$GEN $LOBINC -I$MONO/include -I$UB/include"
LIBS="$LOB/lib/liblobster.a $MONO/lib/libmonocypher.a $UB/lib/libunibreak.a $WXLIBS $GTKLIBS -lpthread -ldl"
HARNESS=$SRC/mayhem/harnesses/ts_fuzz.cpp

# lsan_off: leaks are out of scope; ASan/UBSan stay on (SPEC §6.2 item 15).
$CXX $SANITIZER_FLAGS $DEBUG_FLAGS -c "$SRC/mayhem/lsan_off.cc" -o "$B/lsan_off.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$B/standalone_main.o"

# The TreeSheets side of the Lobster bindings (project code: instrumented). LIBS links it in.
$CXX -std=c++20 -O1 $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link $LOBINC \
     -c "$SRC/src/lobster_impl.cpp" -o "$B/lobster_impl.o" &
pids=($!)
$CXX -std=c++20 -O1 $COVERAGE_FLAGS $LOBINC -c "$SRC/src/lobster_impl.cpp" -o "$B/lobster_impl_plain.o" &
pids+=($!)
for mode in load xml text paste script; do
  M=$(echo "$mode" | tr a-z A-Z)
  $CXX -std=c++20 -O1 $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link -DTS_MODE_$M \
       $DEFS $WXCXX $GTKCFLAGS -c "$HARNESS" -o "$B/ts_${mode}.o" &
  pids+=($!)
done
# Test oracle: the same app code with upstream's normal flags (no sanitizers, no fuzzer).
$CXX -std=c++20 -O1 $COVERAGE_FLAGS -DTS_MODE_ORACLE -DTS_MODE_SCRIPT -DTS_MODE_PASTE $DEFS $WXCXX $GTKCFLAGS -c "$HARNESS" -o "$B/ts_oracle.o" &
pids+=($!)
for p in "${pids[@]}"; do wait "$p"; done

for mode in load xml text paste script; do
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$B/ts_${mode}.o" "$B/lsan_off.o" "$B/lobster_impl.o" $LIBS \
       -o "$SRC/ts_${mode}_fuzzer"
  $CXX $SANITIZER_FLAGS $DEBUG_FLAGS "$B/standalone_main.o" "$B/ts_${mode}.o" "$B/lsan_off.o" "$B/lobster_impl.o" $LIBS \
       -o "$SRC/ts_${mode}_fuzzer-standalone"
done
$CXX $COVERAGE_FLAGS "$B/ts_oracle.o" "$B/lobster_impl_plain.o" $LIBS -o "$B/ts_oracle"
echo "built: $(ls "$SRC"/ts_*_fuzzer*)"
